import DOMPurify from 'dompurify';
import { useEffect, useRef, useState } from 'react';

interface Props {
  src: string;
  alt: string;
  className?: string;
  fill?: string;
}

const svgCache = new Map<string, Promise<string>>();
let instanceCounter = 0;

const purifier = DOMPurify(window);

// <use> is allowed so icons built from <symbol>/<defs> still render, but only
// for in-document fragment references; external refs are a known XSS vector.
purifier.addHook('uponSanitizeAttribute', (node, data) => {
  if (
    node.nodeName.toLowerCase() === 'use' &&
    (data.attrName === 'href' || data.attrName === 'xlink:href') &&
    !data.attrValue.trim().startsWith('#')
  ) {
    data.keepAttr = false;
  }
});

const fetchSvg = (src: string): Promise<string> => {
  let request = svgCache.get(src);

  if (!request) {
    request = fetch(src).then((res) => {
      if (!res.ok) {
        throw new Error(`Request for '${src}' returned ${res.status}`);
      }
      return res.text();
    });
    request.catch(() => svgCache.delete(src));
    svgCache.set(src, request);
  }

  return request;
};

// Replacement IDs are generated by us (never derived from the file), so
// substituting them can't introduce CSS or attribute syntax.
const rewriteIdRefs = (value: string, ids: Map<string, string>): string =>
  value.replace(/url\(\s*(['"]?)#([^'")\s]+)\1\s*\)/g, (match, _quote, id) =>
    ids.has(id) ? `url(#${ids.get(id)})` : match
  );

const rewriteCssRules = (rules: CSSRuleList, ids: Map<string, string>) => {
  for (const rule of Array.from(rules)) {
    if (rule instanceof CSSStyleRule) {
      for (const prop of Array.from(rule.style)) {
        const value = rule.style.getPropertyValue(prop);
        const rewritten = rewriteIdRefs(value, ids);

        if (rewritten !== value) {
          rule.style.setProperty(
            prop,
            rewritten,
            rule.style.getPropertyPriority(prop)
          );
        }
      }
    }

    if ('cssRules' in rule) {
      rewriteCssRules((rule as CSSGroupingRule).cssRules, ids);
    }
  }
};

// Inline <style> applies to the whole page, so confine it to this icon.
// The CSS is round-tripped through CSSOM so the re-serialized text is
// well-formed and can't close the @scope block early.
const scopeCss = (css: string, scope: string, ids: Map<string, string>) => {
  try {
    const sheet = new CSSStyleSheet();
    sheet.replaceSync(css);
    rewriteCssRules(sheet.cssRules, ids);

    const rules = Array.from(sheet.cssRules, (rule) => rule.cssText);
    return `@scope ([data-svg-icon="${scope}"]) {\n${rules.join('\n')}\n}`;
  } catch {
    return '';
  }
};

const buildSvg = (
  markup: string,
  { className, fill }: Pick<Props, 'className' | 'fill'>
): SVGSVGElement | null => {
  const fragment = purifier.sanitize(markup, {
    USE_PROFILES: { svg: true, svgFilters: true },
    ADD_TAGS: ['use'],
    RETURN_DOM_FRAGMENT: true,
  });
  const svg = fragment.querySelector('svg');

  if (!svg) {
    return null;
  }

  const scope = `svg-icon-${++instanceCounter}`;
  const ids = new Map<string, string>();

  svg.querySelectorAll('[id]').forEach((el, i) => {
    const newId = `${scope}-${i}`;
    ids.set(el.id, newId);
    el.id = newId;
  });

  [svg, ...Array.from(svg.querySelectorAll('*'))].forEach((el) => {
    for (const { name, value } of Array.from(el.attributes)) {
      const isRef = name === 'href' || name === 'xlink:href';
      const rewritten =
        isRef && value.startsWith('#') && ids.has(value.slice(1))
          ? `#${ids.get(value.slice(1))}`
          : rewriteIdRefs(value, ids);

      if (rewritten !== value) {
        el.setAttribute(name, rewritten);
      }
    }
  });

  svg.querySelectorAll('style').forEach((style) => {
    style.textContent = scopeCss(style.textContent || '', scope, ids);
  });

  svg.setAttribute('data-svg-icon', scope);
  if (className) svg.setAttribute('class', className);
  if (fill) svg.setAttribute('fill', fill);

  return svg;
};

/**
 * Renders an SVG file inline (so it can inherit theme colors via `fill`)
 * after sanitizing it with DOMPurify. Falls back to <img>, which never runs
 * scripts, if the file can't be fetched or isn't a valid SVG.
 */
export const SvgIcon = ({ src, alt, className, fill }: Props): JSX.Element => {
  const containerRef = useRef<HTMLSpanElement>(null);
  const [fallback, setFallback] = useState<'none' | 'img' | 'hidden'>('none');

  useEffect(() => {
    const container = containerRef.current;
    let cancelled = false;
    setFallback('none');

    fetchSvg(src)
      .then((markup) => {
        if (cancelled || !container) return;

        const svg = buildSvg(markup, { className, fill });

        if (svg) {
          container.replaceChildren(svg);
        } else {
          setFallback('img');
        }
      })
      .catch((err) => {
        if (cancelled) return;
        console.error(err);
        setFallback('img');
      });

    return () => {
      cancelled = true;
      container?.replaceChildren();
    };
  }, [src, className, fill]);

  return (
    <>
      <span ref={containerRef} style={{ display: 'contents' }} />
      {fallback === 'img' && (
        <img
          src={src}
          alt={alt}
          className={className}
          onError={() => setFallback('hidden')}
        />
      )}
    </>
  );
};
